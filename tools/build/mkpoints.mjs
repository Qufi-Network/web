/**
 * The uBTC mark, as points.
 *
 * The scene draws everything as points, so the unit travelling through it has
 * to be points too — a texture pasted on a quad would be the one object in the
 * place that was made of something else. Sampled here at build time rather than
 * from a canvas at runtime: the result is deterministic, costs no decode on the
 * visitor's machine, and the geometry can be built in one pass with everything
 * else.
 */
import fs from 'node:fs';

const { w, h, c, data } = JSON.parse(fs.readFileSync('tools/build/icon-raw.json', 'utf8'));

// A seeded generator, so the mark is the same mark on every machine.
let seed = 0x9e3779b9;
const rng = () => {
  seed ^= seed << 13; seed >>>= 0;
  seed ^= seed >> 17;
  seed ^= seed << 5; seed >>>= 0;
  return seed / 4294967296;
};

const COUNT = 1500;
const points = [];
let guard = 0;
while (points.length < COUNT && guard++ < COUNT * 400) {
  const x = Math.floor(rng() * w);
  const y = Math.floor(rng() * h);
  const i = (y * w + x) * c;
  const a = data[i + 3] / 255;
  if (a < 0.35) continue;
  const r = data[i] / 255, g = data[i + 1] / 255, b = data[i + 2] / 255;
  // Reject in proportion to opacity, so the soft edge thins rather than steps.
  if (rng() > a) continue;
  // The ring is mint; the glyph in the middle is close to white. One number
  // tells them apart, and the shader colours each in its own right.
  const sat = Math.max(r, g, b) - Math.min(r, g, b);
  const glyph = sat < 0.14 ? 1 : 0;
  points.push([
    (x / (w - 1)) * 2 - 1,
    1 - (y / (h - 1)) * 2,
    glyph,
  ]);
}

const glyphs = points.filter((p) => p[2] === 1).length;
console.log('sampled', points.length, 'of which glyph', glyphs);

const q = (v) => Math.round(v * 1000) / 1000;
const body = points.map(([x, y, g]) => `${q(x)},${q(y)},${g}`).join(',');

fs.writeFileSync(
  'assets/ubtc-points.ts',
  `/**
 * The uBTC mark, sampled to points.
 *
 * Generated by \`tools/build/mkpoints.mjs\` from the icon, and checked in rather
 * than sampled at runtime: the scene builds its geometry in one pass on load,
 * and a mark that arrived a moment later would arrive after the buffer it
 * belongs in had been built.
 *
 * Three numbers a point: x and y in -1..1 with the mark's own aspect already in
 * them, and whether the point belongs to the ring or to the glyph inside it.
 */
export const UBTC_POINTS = new Float32Array([${body}]);

/** Points, not numbers. */
export const UBTC_POINT_COUNT = ${points.length};
`,
);
console.log('wrote assets/ubtc-points.ts');
